// Разметка формы кабинета Uzum.
//
// ЭТОТ ФАЙЛ ПОКА ПУСТ, И ЭТО НЕ НЕДОДЕЛКА. Селекторы снимаются с живой страницы кабинета, а
// угаданные означали бы карточку, заполненную не теми полями: название в описание, цена в артикул.
// Пустая форма — это потерянная минута; форма, заполненная неверно и отправленная на модерацию, —
// это товар с чужим описанием в вашем магазине и разбирательство в чужом интерфейсе.
//
// Пока карта пуста, расширение отказывается заполнять что-либо и говорит об этом прямо.
//
// Как заполнить: откройте страницу создания товара, найдите поля в инспекторе и подставьте
// селекторы ниже. Предпочитайте устойчивые признаки — `name`, `data-*`, `aria-label` — классам
// вида `.css-1x2y3z`: сборка фронтенда меняет их при каждом релизе Uzum.

/** Адреса, на которых расширению вообще есть что делать. */
export const CREATE_PAGE = /^https:\/\/seller\.uzum\.uz\/.*\/(product|products)\/(new|create)/i

export const SELECTORS = {
  titleRu: '',
  titleUz: '',
  descriptionRu: '',
  descriptionUz: '',
  category: '',
  price: '',
  // Кнопка отправки — единственное необратимое действие на странице. Отдельно от прочих полей,
  // чтобы её нельзя было нажать «заодно» с заполнением.
  submitButton: '',
}

/**
 * Признаки экранов, на которых надо ОСТАНОВИТЬСЯ и позвать человека.
 *
 * Список намеренно широкий. Ложная остановка стоит одного вашего клика; пропущенная капча или
 * незамеченное модальное окно — нажатия вслепую в кабинете, где нажимать вслепую нельзя.
 */
export const STOP_SIGNS = [
  'iframe[src*="captcha"]',
  'iframe[src*="recaptcha"]',
  'iframe[src*="hcaptcha"]',
  '[class*="captcha" i]',
  '[id*="captcha" i]',
  '[data-testid*="captcha" i]',
]

/** Заполнена ли карта настолько, чтобы можно было хоть что-то делать. */
export function selectorsReady() {
  return Boolean(SELECTORS.titleRu && SELECTORS.category && SELECTORS.submitButton)
}

/** Каких полей не хватает. Список уезжает в журнал: «не сработало» без имён не чинится. */
export function missingSelectors() {
  return Object.entries(SELECTORS).filter(([, value]) => !value).map(([key]) => key)
}
