// Что расширение знает о кабинете Uzum. Здесь осталось ровно три вещи.
//
// Раньше в этом файле лежала карта полей: подписи, плейсхолдеры, лимиты, кнопки. Она переехала в
// content.js и превратилась в набор СМЫСЛОВ — «название», «описание», «русский», «узбекский», — а
// поля ищутся по контексту вокруг них. Карта устаревала при каждой перестройке формы; смыслы не
// устаревают, пока у полей остаются человеческие слова рядом.
//
// Здесь же остаётся то, что к разметке формы не относится: где работать, где остановиться и каким
// словом узнать блок категории.

/**
 * Страница создания товара: /seller/<id магазина>/products/new
 *
 * Адрес узкий намеренно: широкий шаблон означал бы попытку заполнить страницу редактирования уже
 * существующего товара.
 */
export const CREATE_PAGE = /^https:\/\/seller\.uzum\.uz\/seller\/[^/]+\/products\/new/i

/**
 * Слово, по которому узнаётся блок выбора категории.
 *
 * Нужно ровно для одного вывода: если не заполнено НИ ОДНО поле, а поле категории на странице
 * есть, значит владелец ещё не нажал «Принять» и форма закрыта. Это подсказка для сообщения, а не
 * условие работы: не нашли — просто скажем иначе.
 */
export const CATEGORY_HINT = 'категор'

/**
 * Признаки экранов, на которых надо ОСТАНОВИТЬСЯ и позвать человека.
 *
 * Список намеренно широкий. Ложная остановка стоит одного вашего клика; пропущенная капча или
 * незамеченное модальное окно — нажатия вслепую в кабинете, где нажимать вслепую нельзя.
 *
 * Это единственная проверка страницы, которая осталась. Она не про структуру формы, а про то, где
 * действовать нельзя вообще.
 */
export const STOP_SIGNS = [
  'iframe[src*="captcha"]',
  'iframe[src*="recaptcha"]',
  'iframe[src*="hcaptcha"]',
  '[class*="captcha" i]',
  '[id*="captcha" i]',
  '[data-testid*="captcha" i]',
]

/**
 * Краткие описания (лимит 390) Nemo не заполняет.
 *
 * Своего короткого текста у черновика нет, а обрезать полное описание под 390 знаков значит
 * оборвать мысль посреди предложения и отдать это покупателю как аннотацию товара. Поля названы
 * здесь, чтобы следующий, кто их увидит пустыми, не считал это недоделкой.
 */
export const NOT_FILLED = ['Краткое описание товара на русском', 'Краткое описание товара на узбекском']
