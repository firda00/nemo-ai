/**
 * Код без комментариев.
 *
 * Проверять надо исполняемое. Объяснение рядом («подтверждение спрашивается у человека») содержит те
 * же слова, что и проверка, и без среза комментариев она проходила бы на пустом файле с одним
 * комментарием. Такое уже случалось трижды в этом репозитории.
 */
const stripComments = (source) => source
  .replace(/\/\*[\s\S]*?\*\//g, '')
  .replace(/^\s*\/\/.*$/gm, '')

