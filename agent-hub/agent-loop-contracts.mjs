// Границы агентного цикла, записанные проверками.
//
// Цикл сам решает, какой инструмент позвать, по тексту, который писала не модель: содержимое чужого
// сайта, чужая карточка компании. Здесь — то, что легко снять одной строкой ради удобства и не
// заметить последствий: подтверждение действий, конечность цикла, срез пути из имени файла.
//
// Проверки читают ИСХОДНИК, а не поведение: поведение проверяет agent-behavior.mjs. Разница в том, что
// здесь ловится намеренное послабление — «временно уберу подтверждение, чтобы не мешало отлаживать».

import fs from 'node:fs'
import path from 'node:path'

const root = path.resolve(import.meta.dirname, '..')
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8')

/**
 * Код без комментариев.
 *
 * Проверять надо исполняемое. Объяснение рядом («подтверждение спрашивается у человека») содержит те
 * же слова, что и проверка, и без среза комментариев она проходила бы на пустом файле с одним
 * комментарием. Такое уже случалось трижды в этом репозитории.
 */
const stripComments = (source) => source
  .replace(/\/\*[\s\S]*?\*\//g, '')
  .replace(/^\s*\/\/.*$/gm, '')

const runtimeFull = read('agent-hub/agent-runtime.ts')
const runtime = stripComments(runtimeFull)
const platform = stripComments(read('agent-hub/tools/platform.ts'))
const registry = stripComments(read('agent-hub/tools/registry.ts'))
const nemo = stripComments(read('agent-hub/nemo.mjs'))
const ui = stripComments(read('agent-hub/nemo-ui.mjs'))
const commands = stripComments(read('agent-hub/cli/commands.ts'))
const commandsFull = read('agent-hub/cli/commands.ts')
const wiring = stripComments(read('agent-hub/cli/wiring.ts'))
const pkg = JSON.parse(read('package.json'))

const failures = []
const must = (condition, message) => { if (!condition) failures.push(message) }

// ─── Подтверждение действий ───────────────────────────────────────────────────────────────────────

must(
  /permission === 'action'/.test(runtime),
  'цикл больше не различает права инструмента: действие выполнится наравне с чтением',
)
must(
  /if \(!this\.deps\.confirm\)/.test(runtime),
  'нет запрета выполнять действие, когда спросить некого — в неинтерактивном режиме оно пройдёт молча',
)
must(
  /const approved = await this\.deps\.confirm\(/.test(runtime) && /if \(!approved\)/.test(runtime),
  'отказ человека больше не останавливает действие',
)
// Отказ уходит модели РЕЗУЛЬТАТОМ. Молчание вместо результата хуже: модель отчитается об отправке как
// о сделанной, и человек узнает правду через день по отсутствию реакции клиента.
must(
  /code: 'permission_denied'/.test(runtime),
  'отказ не доходит до модели результатом — она сочтёт действие выполненным',
)

// Наружу разговора выходят ровно два инструмента, и оба помечены действием. Остальные помечены
// чтением намеренно: спрашивать на каждое сохранение отчёта — верный способ приучить человека жать
// «да» не глядя, и тогда он так же нажмёт «да» на отправке карточки не тому клиенту.
for (const name of ['telegram_send_lead', 'crm_sync_lead']) {
  const block = platform.slice(platform.indexOf(`name: '${name}'`))
  must(
    /permission: 'action'/.test(block.slice(0, 400)),
    `${name} отправляет данные наружу, но больше не помечен действием`,
  )
}

// ─── Конечность цикла ─────────────────────────────────────────────────────────────────────────────

must(
  /for \(let step = 1; step <= this\.maxSteps; step\+\+\)/.test(runtime),
  'цикл шагов больше не ограничен: модель, зовущая инструмент подряд, не остановится',
)
must(
  /Остановился после \$\{this\.maxSteps\} шагов/.test(runtime),
  'исчерпание шагов молчит — оборванная работа выглядит как законченный ответ',
)
must(
  /export const MAX_STEPS = \d+/.test(runtimeFull),
  'предел шагов перестал быть именованной величиной',
)

// ─── Правда о результате ──────────────────────────────────────────────────────────────────────────

must(
  /РЕЗУЛЬТАТ ОБРЕЗАН/.test(runtime),
  'обрезка результата стала молчаливой: модель примет обрывок за полные данные',
)
must(
  /НЕ сообщай о выполненном действии/.test(runtimeFull),
  'из системного промпта пропал запрет отчитываться о невыполненном',
)
must(
  /НЕ выдумывай телефоны/.test(runtimeFull),
  'из системного промпта пропал запрет выдумывать контакты',
)

// ─── Парность событий рамки ───────────────────────────────────────────────────────────────────────
//
// tool_start рисует открытую рамку, tool_end закрывает её. Оба события живут в ОДНОЙ функции: пока они
// стояли в разных местах, каждый ранний выход давал либо висящий короб, либо низ рамки без верха. Оба
// варианта случились на прогонах.

const runCall = runtime.slice(runtime.indexOf('private async runCall'), runtime.indexOf('private async attemptCall'))
must(
  /type: 'tool_start'/.test(runCall) && /type: 'tool_end'/.test(runCall),
  'события начала и конца вызова разъехались по разным функциям — рамка в терминале снова останется незакрытой',
)
must(
  !/type: 'tool_start'|type: 'tool_end'/.test(runtime.slice(runtime.indexOf('private async attemptCall'))),
  'событие рамки вернулось внутрь attemptCall, где ранний выход его пропускает',
)

// ─── Имя файла из ответа модели ───────────────────────────────────────────────────────────────────

must(
  /path\.basename\(/.test(platform),
  'из имени файла перестали срезать путь: `../../.secrets.local` в этом поле попадёт на диск как есть',
)
must(
  /\[\^\\p\{L\}\\p\{N\}_-\]/.test(platform),
  'имя файла больше не очищается от посторонних знаков',
)

// ─── Реестр инструментов ──────────────────────────────────────────────────────────────────────────

must(
  /allowedActions/.test(registry) || /allowed/.test(registry),
  'реестр перестал спрашивать разрешение на действие — запрет по умолчанию снят',
)
// Инструмент без зависимости не регистрируется вовсе: зарегистрированный, но неработающий модель
// увидит, предложит человеку и вызовет — а получит отказ, потратив токены и время.
must(
  /skipped/.test(platform),
  'сборка реестра перестала отсеивать ненастроенные инструменты',
)

// ─── Точка входа ──────────────────────────────────────────────────────────────────────────────────

must(pkg.scripts?.nemo, 'исчезла точка входа npm run nemo')
must(
  pkg.scripts?.['sdr:run']?.includes('sdr-run.mjs'),
  'сломан старый режим флагов npm run sdr:run, на котором стоят cron и скрипты',
)
must(
  /isInteractiveTerminal\(\)/.test(nemo),
  'агент запускается без терминала: в конвейере он повиснет на первом же вопросе о подтверждении',
)
must(
  /stopActiveSpinner\(\)/.test(nemo),
  'спиннер не гасится перед вопросом — анимация затрёт набираемый ответ (ошибка уже возвращалась дважды)',
)
// Умолчание — ОТКАЗ. Enter на вопросе об отправке сообщения живому человеку не должен означать
// согласие: цена ошибки здесь несимметрична.
must(
  /\['д', 'да', 'y', 'yes', 'ага'\]\.includes\(answer\)/.test(nemo),
  'согласие определяется не списком «да» — пустой ввод может пройти как подтверждение',
)

// ─── Отрисовка ────────────────────────────────────────────────────────────────────────────────────

must(
  /visibleWidth/.test(ui),
  'ширина рамки считается по длине строки, а не по видимым знакам — цвет разъедет рамку',
)
must(
  /outcome\.ok \? summarize\(outcome\.result\) : /.test(ui),
  'низ рамки перестал показывать причину отказа — неудачный вызов выглядит как успешный',
)


// ─── Слеш-команды: целостность истории ────────────────────────────────────────────────────────────
//
// Реплика модели с вызовами инструментов и результаты этих вызовов образуют неразрывную группу. Любая
// операция, режущая историю посередине, оставляет результат без заказавшей его реплики, и провайдер
// отвергает СЛЕДУЮЩИЙ запрос целиком — человек видит «модель не отвечает» через минуту после команды,
// без видимой связи с ней.

must(
  /findLastIndex\(\(one\) => one\.role === 'user'\)/.test(runtime),
  'отмена хода перестала искать границу по реплике человека — снимет результат инструмента без его вызова',
)
must(
  /const cut = userAt\[userAt\.length - keepTurns\]/.test(runtime),
  'сжатие режет историю по числу сообщений, а не по ходам — разорвёт группу «вызовы → результаты»',
)
must(
  /const at = this\.messages\.findIndex\(\(one\) => one\.role === 'system'\)/.test(runtime),
  'смена роли перестала заменять системный промпт на месте — две системные реплики будут спорить друг с другом',
)
must(
  /if \(system\) this\.messages\.push\(system\)/.test(runtime),
  '/clear стирает системный промпт вместе с историей — роль молча сбросится на общую',
)

// ─── Ключ не уходит на чужой адрес ────────────────────────────────────────────────────────────────

must(
  /const authorized = baseUrl === OPENROUTER_BASE/.test(runtime),
  'ключ OpenRouter уходит по любому адресу: `/model local` раздаст его процессу, занявшему порт 11434',
)
must(
  /authorized\s*\n?\s*\? \{ Authorization/.test(runtime),
  'заголовок с ключом ставится безусловно',
)

// ─── Роли ─────────────────────────────────────────────────────────────────────────────────────────

for (const role of ['general', 'sdr', 'dev', 'qa', 'media']) {
  must(commands.includes(`\n  ${role}: {`), `исчезла роль ${role}`)
}
// У проверяющей и медийной ролей нет доступа к боевым данным: случайный вызов во время проверки задел
// бы живых людей.
for (const role of ['qa', 'media']) {
  const block = commands.slice(commands.indexOf(`  ${role}: {`), commands.indexOf(`  ${role}: {`) + 900)
  must(!/telegram_send_lead/.test(block), `роль ${role} получила право отправлять карточки клиентам`)
  must(!/crm_sync_lead/.test(block), `роль ${role} получила право писать в CRM`)
}
must(
  /export function restrictRegistry/.test(registry),
  'исчезло сужение реестра по роли — роль перестанет ограничивать инструменты',
)
must(
  /const narrowed = new ToolRegistry\(\)/.test(registry),
  'сужение роли работает поверх исходного реестра — возврат к роли general потеряет инструменты навсегда',
)

// ─── Универсальный промпт ─────────────────────────────────────────────────────────────────────────

must(
  /export const UNIVERSAL_MISSION/.test(runtimeFull),
  'исчезла универсальная роль по умолчанию',
)
must(
  !/ассистент платформы Nemo AI для B2B-продаж/.test(runtime),
  'в общий промпт вернулась привязка к B2B-продажам — агент снова откажется разбирать логи и собирать видео',
)
must(
  /Круг задач не ограничен продажами/.test(runtimeFull),
  'из промпта пропало прямое указание, что круг задач шире продаж',
)

// ─── Правда о результате команд ───────────────────────────────────────────────────────────────────

must(
  /\[Нн\]е выдумывай|Не выдумывай ничего/.test(commandsFull),
  'из просьбы о пересказе пропал запрет выдумывать: сжатие с придуманным телефоном отравит весь остаток разговора',
)
must(
  /Ничего не выдумывай/.test(commandsFull),
  'из /scrape пропал запрет выдумывать — вернёт выдуманные контакты',
)
must(
  /не удалось узнать/.test(commands),
  'неудача запроса баланса выглядит как остаток — человек пойдёт пополнять счёт, на котором деньги есть',
)
must(
  /`нет \$\{missing\.join\(', '\)\}/.test(wiring),
  'проверка зависимостей перестала называть недостающий ключ',
)

// Выгрузка сессии не выносит аргументы вызовов: файл легко уходит в чат, а в аргументах телефоны.
must(
  /one\.function\.name/.test(commands) && !/one\.function\.arguments/.test(commands),
  'выгрузка сессии выносит аргументы вызовов — телефоны найденных людей утекут вместе с файлом',
)
must(
  /if \(message\.role === 'system'\) continue/.test(commands),
  'выгрузка сессии выносит системный промпт',
)

// ─── Точка входа ──────────────────────────────────────────────────────────────────────────────────

must(pkg.scripts?.['test:cli-commands'], 'проверки слеш-команд не подключены к гейту')
must(
  /completer/.test(nemo),
  'исчезло автодополнение по Tab',
)
must(
  /toolBadges\(/.test(nemo),
  'вернулся список «недоступно» вместо строки состояния — старт снова читается как пять поломок',
)
must(
  !/недоступно:/.test(nemo.replace(/if \(debug\)[\s\S]*?\n\}/, '')),
  'список недоступного вернулся в обычный вывод (в режиме --debug он уместен)',
)
must(
  /connectMcpServers\(/.test(nemo),
  'MCP-серверы перестали подключаться при старте',
)

if (failures.length) {
  console.error('[FAIL] Agent loop contracts')
  for (const failure of failures) console.error(`  - ${failure}`)
  process.exit(1)
}
console.log(`[OK] Agent loop contracts: ${failures.length === 0 ? 'все границы на месте' : ''}`)
