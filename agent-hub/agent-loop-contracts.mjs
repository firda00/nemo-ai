/**
 * Кусок исходника от объявления роли до её закрывающей скобки.
 *
 * По границе, а не по фиксированной длине: окно в 1200 знаков перестало доставать до списка
 * инструментов, как только промпты ролей выросли, — и контракт объявил, что роль потеряла браузер,
 * хотя браузер был на месте. Проверка, ломающаяся от правки соседнего текста, хуже её отсутствия.
 */
const roleBlock = (name) => {
  const start = roles.indexOf(`
  ${name}: {`)
  if (start < 0) return ''
  const end = roles.indexOf('\n  },', start)
  return end < 0 ? roles.slice(start) : roles.slice(start, end)
}

