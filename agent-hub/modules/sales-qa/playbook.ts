/*
 * Скрипты продаж как ДАННЫЕ, а не как код.
 *
 * ОТКУДА ЭТО ВЗЯЛОСЬ. В исходном модуле (MetaSell, server/playbook.js) сценарий был константой
 * USTUDY_SALES_SCRIPT: этапы одного заказчика, зашитые в файл, плюс двадцать четыре упоминания его
 * имени по коду. Такой модуль продаётся ровно одному клиенту — второму он достаётся только вместе
 * с правкой исходников, а третий получает форк.
 *
 * Здесь сценарий — структура, которую передают: по идентификатору из каталога или целиком в
 * параметре. Ни одного названия компании в коде нет, и контракт за этим следит.
 *
 * ЧТО ОСТАЛОСЬ ОТ ОРИГИНАЛА. Форма разбора: этапы с весами, критерии с оценкой 0–3, обязательное
 * дословное доказательство. Это и есть ценная часть — она не про конкретного заказчика, а про то,
 * как вообще проверять разговор, не веря модели на слово.
 */

/** Один этап разговора: что менеджер должен был сделать и насколько это важно. */
export interface PlaybookStage {
  /** Порядковый номер, с единицы. По нему модель отчитывается, и он же держит порядок в отчёте. */
  id: number
  /** Короткое имя этапа для человека. */
  title: string
  /** Что именно считается выполнением. Уходит в промпт как определение, а не как намёк. */
  expectation: string
  /**
   * Вес этапа в итоговом балле.
   *
   * Не «важность» на глаз: сумма весов задаёт знаменатель. Этап с весом 0 проверяется и
   * показывается, но на балл не влияет — так помечают необязательные части разговора.
   */
  weight: number
  /**
   * Может ли этап оказаться НЕПРИМЕНИМЫМ в конкретном разговоре.
   *
   * Неприменимый этап исключается из знаменателя — то есть не портит оценку. Ровно поэтому право
   * объявить этап неприменимым нельзя отдавать модели: пометив пять этапов из шести неприменимыми и
   * подтвердив шестой, она получает сто процентов из ничего, и по отчёту это выглядит безупречно.
   *
   * Поэтому решение принимает СЦЕНАРИЙ, а не разбор. Условным бывает то, чего в разговоре могло не
   * случиться по вине собеседника: возражение, которого он не высказал. «Менеджер не представился»
   * условным не бывает никогда.
   */
  optional?: boolean
}

/** Критерий сквозной оценки — то, что относится ко всему разговору, а не к одному этапу. */
export interface PlaybookCriterion {
  code: string
  title: string
  expectation: string
}

export interface Playbook {
  id: string
  title: string
  /** Язык разговора. Влияет на промпт: оценивать узбекский по русским нормам бессмысленно. */
  language: string
  stages: PlaybookStage[]
  criteria: PlaybookCriterion[]
}

