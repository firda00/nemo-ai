/**
 * Проверка сценария перед работой.
 *
 * Плохой сценарий приходит из конфига заказчика, а не из нашего кода, — и молча даёт бессмысленный
 * отчёт: дубли этапов путают модель, нулевая сумма весов обнуляет знаменатель, пустое ожидание
 * оставляет этап без определения, и модель придумывает его сама.
 */
export function validatePlaybook(playbook: Playbook): string[] {
  const problems: string[] = []
  if (!playbook?.id?.trim()) problems.push('у сценария нет идентификатора')
  if (!Array.isArray(playbook?.stages) || playbook.stages.length === 0) problems.push('в сценарии нет ни одного этапа')

  const ids = (playbook.stages ?? []).map((stage) => stage.id)
  if (new Set(ids).size !== ids.length) problems.push('идентификаторы этапов повторяются')
  if (ids.some((id) => !Number.isInteger(id) || id < 1)) problems.push('идентификатор этапа должен быть целым числом с единицы')

  for (const stage of playbook.stages ?? []) {
    if (!stage.expectation?.trim()) problems.push(`этап ${stage.id} без описания ожидаемого`)
    if (!Number.isFinite(stage.weight) || stage.weight < 0) problems.push(`этап ${stage.id} с недопустимым весом`)
  }
  const total = (playbook.stages ?? []).reduce((sum, stage) => sum + (stage.weight || 0), 0)
  if (total <= 0) problems.push('сумма весов равна нулю — итоговый балл посчитать не из чего')

  const codes = (playbook.criteria ?? []).map((one) => one.code)
  if (new Set(codes).size !== codes.length) problems.push('коды критериев повторяются')

  return problems
}

/** Каталог сценариев в памяти процесса. Заказчик кладёт сюда свои при запуске. */
export class PlaybookCatalog {
  private readonly items = new Map<string, Playbook>()

  constructor(initial: Playbook[] = [DEFAULT_PLAYBOOK]) {
    for (const one of initial) this.add(one)
  }

  /**
   * Добавить сценарий. Негодный ОТВЕРГАЕТСЯ, а не принимается молча: сценарий с нулевыми весами,
   * принятый сейчас, выдаст деление на ноль через час, и связь с этим вызовом уже не увидят.
   */
  add(playbook: Playbook): void {
    const problems = validatePlaybook(playbook)
    if (problems.length) throw new Error(`сценарий «${playbook?.id ?? '?'}» негоден: ${problems.join('; ')}`)
    this.items.set(playbook.id, playbook)
  }

  get(id: string): Playbook | null {
    return this.items.get(id) ?? null
  }

  list(): Array<{ id: string; title: string; stages: number }> {
    return [...this.items.values()].map((one) => ({ id: one.id, title: one.title, stages: one.stages.length }))
  }
}
