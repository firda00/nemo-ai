import assert from 'node:assert/strict'
import fs from 'node:fs'

const read = (path) => fs.readFileSync(new URL(`../${path}`, import.meta.url), 'utf8')
const dashboard = read('src/components/finance/FinanceCashFlowDashboard.tsx')
const client = read('src/lib/financeReportClient.ts')
const desk = read('src/components/platform/SmartTaskDesk.tsx')
const app = read('src/App.tsx')
const layout = read('src/components/layout/AppLayout.tsx')

assert.match(app, /path="finance" element=\{<Navigate to="\/app" replace \/>\}/, 'legacy finance links must reach the main workspace')
assert.match(layout, /to: '\/app'/, 'the main workspace must be discoverable in product navigation')
assert.match(desk, /kind: 'finance' as const, label: t\('smartTaskDesk\.suggestionFinance'\)/, 'the main chat must offer its finance entry')
assert.match(desk, /kind === 'finance' && <FinanceCashFlowDashboard \/>/, 'the finance task must mount the actual dashboard inside the chat')
assert.match(dashboard, /await requestFinanceReport\(/, 'dashboard must use the scoped report client')
assert.match(client, /analysis: CashFlowAnalyticsOutputSchema/, 'backend analysis must use the canonical Zod schema')
assert.match(client, /ResultSchema\.parse\(body\)/, 'all result fields must be validated')
assert.match(client, /deps\.fetch\('\/api\/finance\/analyze-cashflow'/, 'client must call the product cash-flow endpoint')
assert.match(client, /Authorization: `Bearer \$\{session\.token\}`/, 'request must include the captured authenticated session')
assert.match(client, /session\.userId !== scope\.userId/, 'client must reject a different session owner')
assert.match(client, /expected\.summary/, 'displayed totals must be checked against returned transactions')
assert.match(dashboard, /financeCalendarPeriod\(/, 'day and month boundaries must use the shared calendar implementation')
assert.match(dashboard, /financePeriod\.demoOrders/, 'example orders must be clearly identified as demonstration data')
assert.match(dashboard, /MAX_BYTES = 8 \* 1024 \* 1024/, 'ingestion must enforce the 8 MB file limit')
assert.match(dashboard, /MAX_ROWS = 10_000/, 'ingestion must enforce the 10,000-row limit')
assert.match(dashboard, /format !== 'excel_json' && format !== 'pdf_json'/, 'binary Excel/PDF must be represented by safe JSON dumps')
assert.match(dashboard, /accept="\.csv,\.json,text\/csv,application\/json"/, 'dropzone must reject raw binary formats')
assert.match(dashboard, /requires_human_approval: true/, 'recommendations must preserve the human approval invariant')
assert.match(dashboard, /decide\(draft\.id, 'approved'\)/)
assert.match(dashboard, /decide\(draft\.id, 'rejected'\)/)
assert.match(dashboard, /buildPrintableDocument/, 'order drafts must support printable PDF export')
assert.doesNotMatch(dashboard, /functions\.invoke\([^)]*(execute|publish|send|pay)/i, 'approval UI must not execute external actions')

console.log('[OK] Finance dashboard UI: grounded cash flow, safe ingestion and human-reviewed order drafts')
