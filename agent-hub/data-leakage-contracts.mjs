import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8')
const migration = read('supabase/migrations/20260803150000_data_leakage_hardening.sql')
const oauth = read('supabase/functions/google-oauth/index.ts')
const browser = read('supabase/functions/browser-bridge/index.ts')
const redact = read('supabase/functions/_shared/redact.ts')
const workflow = read('src/pages/app/EducationSalesWorkflowPage.tsx')
const auth = read('src/context/AuthContext.tsx')
const audioUi = read('src/components/platform/OpsWorkflowRunner.tsx')
const transcribe = read('supabase/functions/transcribe-file/index.ts')
const functionSources = fs.readdirSync(path.join(root, 'supabase/functions'), { recursive: true })
  .filter((file) => String(file).endsWith('.ts'))
  .map((file) => fs.readFileSync(path.join(root, 'supabase/functions', String(file)), 'utf8'))
  .join('\n')
const renderService = read('render-worker/deploy/nemo-render.service')
const renderPackage = read('render-worker/package.json')
const renderReadme = read('render-worker/README.md')

assert.match(migration, /google_oauth_transactions/)
assert.match(migration, /consume_google_oauth_transaction/)
assert.match(migration, /used_at is null[\s\S]*expires_at > now\(\)/, 'OAuth state must be single-use and expiring')
assert.match(oauth, /crypto\.randomUUID\(\) \+ crypto\.randomUUID\(\)/)
assert.match(oauth, /consume_google_oauth_transaction/)
assert.doesNotMatch(oauth, /makeState|readState|hmac\(/, 'OAuth state must not be a reusable signed account id')
assert.match(migration, /'private-audio'[\s\S]*false/, 'audio bucket must be private')
assert.match(audioUi, /storage\.from\('private-audio'\)/)
assert.match(transcribe, /const MEDIA_BUCKET = 'private-audio'/)
assert.doesNotMatch(transcribe, /object\/public/, 'transcription must not accept public storage URLs')
assert.doesNotMatch(workflow, /localStorage\.setItem\(['"]nemo-(?:workflow|saved-report|yc-waitlist)/, 'workflow PII must not enter localStorage')
assert.match(auth, /clearAccountLocalData/)
assert.match(auth, /nemo-workflow-input/)
assert.match(browser, /parsed\.search = ''[\s\S]*parsed\.hash = ''/)
assert.match(browser, /slice\(0, 8000\)/)
assert.match(redact, /EMAIL REDACTED/)
assert.match(redact, /PHONE REDACTED/)
assert.match(redact, /JWT REDACTED/)
assert.match(migration, /interval '24 hours'/)
assert.match(browser, /clear_observations/)
assert.doesNotMatch(functionSources, /supabase-js@2['"]/, 'Edge Function dependencies must not use a mutable major tag')
assert.match(functionSources, /supabase-js@2\.108\.2/, 'Edge Functions must use the reviewed exact Supabase client version')
assert.match(renderService, /DynamicUser=true/)
assert.match(renderService, /ProtectSystem=strict/)
assert.match(renderService, /CapabilityBoundingSet=/)
assert.doesNotMatch(renderPackage, /"(?:@supabase\/supabase-js|express)":\s*"[~^]/, 'render worker runtime dependencies must be exact')
assert.match(renderReadme, /npm ci --omit=dev/)
assert.ok(fs.existsSync(path.join(root, 'render-worker/package-lock.json')), 'render worker lockfile must exist')

console.log('Data leakage hardening contracts passed.')
