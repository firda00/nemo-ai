// Разбор запроса, набранного одной фразой: «стоматология в Ташкенте 15 лидов».
//
// Смысл — чтобы человек не проходил четыре вопроса, когда всё уже сказано одной строкой. Разбор
// НАМЕРЕННО осторожный: чего он не понял, то останется пустым и будет спрошено отдельно. Угадать
// город неверно хуже, чем спросить: прогон уйдёт в другую страну, потратит кредиты и вернёт
// «ничего не найдено» без объяснения.

/** Слова-паразиты вокруг числа: «15 лидов», «до 25 компаний», «50 штук». */
const COUNT_WORDS = 'лид(?:ов|а|)|компан(?:ий|ии|ия)|штук(?:и|)|фирм(?:ы|)|мест'
const COUNT_RE = new RegExp(`(?:^|\\s)(?:до\\s+)?(\\d{1,3})(?:\\s*(?:${COUNT_WORDS}))?(?=\\s|$)`, 'i')

/**
 * Предлог места — только его позиция. «во» отдельно: «во Владимире».
 *
 * Ищутся ВСЕ предлоги и берётся ПОСЛЕДНИЙ: «вода в бутылках в Фергане» по первому даёт город
 * «бутылках в Фергане». Название места в русской фразе идёт последним, а всё до него — описание ниши.
 * Регексп намеренно не захватывает сам город: выражение, дотянутое до конца строки, поглощает
 * следующие предлоги и превращается в ОДНО совпадение — тогда «последнее» и «первое» совпадают.
 */
const PREPOSITION_RE = /\s(?:в|во)\s+/gi

const MIN_LIMIT = 1
const MAX_LIMIT = 200

/**
 * Название места из хвоста после предлога.
 *
 * Первое слово берётся всегда, дальше — только пока слова начинаются с ЗАГЛАВНОЙ. Без этого правила
 * «в Ташкенте стоматологии» (город впереди — совершенно обычный порядок слов) отдавало городом
 * «Ташкенте стоматологии» и оставляло нишу пустой. Заглавная буква — единственный признак,
 * отличающий «Нижнем Новгороде» (два слова, одно место) от «Ташкенте стоматологии» (место и ниша).
 * Если человек пишет строчными, останавливаемся на первом слове: «в ташкенте стоматологии» → город
 * «ташкенте», ниша «стоматологии», а падеж потом снимет resolveCityBBox.
 */
function cityFromTail(tail) {
  const words = tail.split(',')[0].trim().split(/\s+/).filter(Boolean)
  if (!words.length) return null
  const taken = [words[0]]
  for (const word of words.slice(1)) {
    // Число здесь — это остаток лимита, не часть названия: «в Ташкенте 500» (500 больше верхней
    // границы, поэтому лимитом не стал) не должно давать город «Ташкенте 500».
    if (!/^\p{Lu}/u.test(word)) break
    taken.push(word)
  }
  return taken.join(' ')
}

/**
 * Фраза → параметры прогона.
 *
 * Возвращает то, что удалось понять, и НЕ придумывает остального: `city: null` означает «спроси»,
 * а не «возьми Ташкент». Значение по умолчанию — решение интерфейса, а не разбора.
 */
export function parseNaturalQuery(text) {
  const raw = String(text ?? '').trim()
  if (!raw) return { query: null, city: null, limit: null, rest: '' }

  let working = ` ${raw} `

  // Число вынимается ПЕРВЫМ: иначе «15» уедет в название ниши или в город.
  let limit = null
  const count = working.match(COUNT_RE)
  if (count) {
    const parsed = Number(count[1])
    if (parsed >= MIN_LIMIT && parsed <= MAX_LIMIT) {
      limit = parsed
      working = working.replace(count[0], ' ')
    }
  }

  // Город — по предлогу. Без предлога не угадываем: «стоматология Ташкент» может быть названием
  // сети, и разобрать это надёжно нельзя.
  let city = null
  const preposition = [...working.matchAll(PREPOSITION_RE)].at(-1)
  if (preposition) {
    const tail = working.slice(preposition.index + preposition[0].length)
    const name = cityFromTail(tail)
    if (name) {
      city = name
      // Вырезаем по ПОЗИЦИИ найденного предлога, а не по тексту: replace() при повторяющемся предлоге
      // убрал бы первое вхождение, оставив в нише как раз название города.
      working = `${working.slice(0, preposition.index)} ${tail.slice(tail.indexOf(name) + name.length)}`
    }
  }

  // Знаки, оставшиеся на месте вынутых частей: «кофейни в Бухаре, 10 штук» иначе даёт нишу
  // «кофейни ,» — и она поедет в чужой API ровно в таком виде.
  const query = working.replace(/\s+/g, ' ').replace(/^[\s,;.·—-]+|[\s,;.·—-]+$/g, '').trim() || null
  return { query, city, limit, rest: raw }
}

/** Похоже ли, что человек ввёл команду, а не запрос. */
export function parseCommand(text) {
  const raw = String(text ?? '').trim()
  if (!raw.startsWith('/')) return null
  const [name, ...args] = raw.slice(1).split(/\s+/)
  return { name: name.toLowerCase(), args }
}

export { MAX_LIMIT, MIN_LIMIT }
