import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8')
const migration = read('supabase/migrations/20260803110000_owner_approval_queue.sql')
const api = read('supabase/functions/approval-queue/index.ts')
const page = read('src/pages/app/ApprovalsPage.tsx')
const agentTool = read('supabase/functions/agent-tool/index.ts')
const actionPolicy = read('supabase/functions/_shared/agentActionPolicy.ts')
const conversationTools = read('supabase/functions/_shared/tools.ts')
const builder = read('src/pages/app/CreateAgentPage.tsx')
const policyMigration = read('supabase/migrations/20260803120000_agent_action_policy.sql')
const reviewMigration = read('supabase/migrations/20260804130000_research_review_inbox.sql')

assert.match(migration, /references public\.accounts\(id\) on delete cascade/, 'approval requests must be tenant-owned')
assert.match(migration, /enable row level security/, 'approval queue must be RLS protected')
assert.match(migration, /revoke all on public\.approval_requests from anon, authenticated/, 'browser roles must not read or alter approvals directly')
assert.match(api, /eq\('account_id', profile\.account_id\)/, 'every list and decision must be account-scoped')
assert.match(api, /profile\.role !== 'owner'/, 'operators must not read or decide owner approvals')
assert.match(api, /eq\('status', 'pending'\)/, 'a decision must be atomic and cannot overwrite a prior decision')
assert.match(api, /A future executor must separately/, 'approval must not silently become execution')
assert.match(page, /t\('approvals\.subtitle'\)/, 'the localized owner UI must explain the execution boundary')
assert.match(agentTool, /guardAgentAction\(admin, accountId, name, args/, 'integration tester must use the shared execution guard')
assert.match(conversationTools, /guardAgentAction\(db, accountId, name, args/, 'conversational tools must use the same guard')
assert.match(actionPolicy, /queueAgentApproval[\s\S]*'browser_mutation'[\s\S]*'browser'/, 'blocked browser mutations must become browser approval requests')
assert.match(actionPolicy, /Действие не выполнено\. Создан owner approval request/, 'the tool must never claim a queued action happened')
assert.match(actionPolicy, /name === 'browser_task' && browserValidation === null/, 'only a browser task that passed validation is an explicit read')
assert.match(actionPolicy, /source: 'agent' \| 'browser' = 'agent'/, 'agent mutations must enter the owner queue')
assert.match(agentTool, /eq\('id', agentId\)\.eq\('account_id', accountId\)/, 'an action policy lookup must be tenant-scoped')
assert.match(actionPolicy, /policy === 'read_only'/, 'read-only agents must block mutation intents')
assert.match(builder, /Draft \+ owner approval/, 'agent builder must expose the approval policy')
assert.match(policyMigration, /check \(action_policy in \('read_only', 'approval_required'\)\)/, 'the database must reject unsupported executor policies')
assert.match(reviewMigration, /after insert or update of status on public\.research_runs/, 'research escalation must create owner work transactionally')
assert.match(reviewMigration, /source = 'workflow' and action_type = 'research_quality_review'/, 'one quality-review request must exist per run')
assert.match(reviewMigration, /create or replace function public\.decide_approval_request/, 'queue and report decisions must share one transaction')
assert.match(reviewMigration, /status = 'pending' and expires_at > now\(\)/, 'expired requests must not be decidable')
assert.match(reviewMigration, /revoke update, delete on public\.research_runs from anon, authenticated/, 'browser roles must not forge or erase review decisions')
assert.match(reviewMigration, /on delete set null/, 'deleting a report must retain the approval audit record')
assert.match(reviewMigration, /jsonb_typeof\(run\.steps\) = 'array'/, 'legacy malformed review JSON must not abort the backfill')
assert.match(reviewMigration, /human_review_status = p_decision[\s\S]*status = case when p_decision = 'approved'/, 'owner decisions must resolve the linked report')
assert.match(reviewMigration, /where status = 'needs_review' and human_review_status is null/, 'existing escalated reports must be backfilled')
assert.match(api, /rpc\('decide_approval_request'/, 'the API must use the atomic decision RPC')
assert.match(api, /\.eq\('status', 'pending'\)[\s\S]*\.neq\('status', 'pending'\)/, 'pending owner work must be listed before history')
assert.match(page, /related_research_run_id[\s\S]*t\('approvals\.openReport'\)/, 'workflow reviews must link to the localized report action')
assert.match(page, /invokeError \|\| !payload\?\.ok/, 'queue failures must not render as an empty inbox')
console.log('Approval queue contracts passed.')
