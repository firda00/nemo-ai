// отправить карточку клиенту, даже если модель решит, что так полезнее. Роль сужает набор и никогда его
// не расширяет: имени, которого нет в реестре, она включить не может.

/**
 * Роль.
 *
 * `tools: null` — все зарегистрированные инструменты. Список имён — только они, и только если они
 * действительно настроены. Имя может содержать `*` на конце: `mcp__*` берёт все инструменты
 * подключённых MCP-серверов, число и имена которых заранее неизвестны.
 */
export interface AgentRole {
  readonly name: string
  readonly title: string
  readonly mission: string
  readonly tools: readonly string[] | null
}

