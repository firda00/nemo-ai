/**
 * Промпт роли целиком: справка о платформе, общий хвост, правило доступа и специализация.
 *
 * Собирается функцией, а не склеивается в каждом месте вызова: мест таких три (старт, /agent, тесты),
 * и забытая склейка в одном из них означала бы роль без контекста платформы — молча.
 */
export function missionFor(role: AgentRole): string {
  // tools === null — весь реестр инструментов, передавать некуда.
  const access = role.tools === null ? FULL_ACCESS_RULE : HANDOFF_RULE
  const parts = [PLATFORM_CONTEXT, ANSWER_ANYWAY, access]
  if (role.mission.trim()) parts.push(role.mission)
  return parts.join('\n\n')
}

