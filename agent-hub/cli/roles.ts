//
// ПОЧЕМУ ПЯТЬ НЕЗАВИСИМЫХ ПРОМПТОВ, А НЕ ОДИН С ДОБАВКАМИ. Общая часть была: каждая роль начиналась с
// «Nemo ищет компании по нише и городу», и дальше шла специализация. Роль `dev` при этом на просьбу
// разобрать ошибку в коде предлагала поискать компании — потому что первое, что она о себе читала, было
// про поиск компаний. Общий текст не нейтрален: он задаёт умолчание, к которому модель возвращается
// каждый раз, когда задача неочевидна.
//
// ОГРАНИЧЕНИЕ ИНСТРУМЕНТОВ — ТОЖЕ ЧАСТЬ РОЛИ, и не косметическая. Роль `qa` не должна иметь возможности
// отправить карточку клиенту, даже если модель решит, что так полезнее. Роль сужает набор и никогда его
// не расширяет: имени, которого нет в реестре, она включить не может.

/**
 * Роль.
 *
 * `tools: null` — все зарегистрированные инструменты. Список имён — только они, и только если они
 * действительно настроены. Имя может содержать `*` на конце: `mcp__*` берёт все инструменты
 * подключённых MCP-серверов, число и имена которых заранее неизвестны.
 */
export interface AgentRole {
  readonly name: string
  readonly title: string
  readonly mission: string
  readonly tools: readonly string[] | null
}

