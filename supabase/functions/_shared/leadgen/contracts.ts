// Контракты сервисов лидогенерации.
//
// Здесь описано, ЧТО каждый сервис обязан уметь, и ничего о том, как он это сделает. Разделение не
// ради красоты: три из пяти сервисов ходят в чужие платные API, и подменить их заглушкой на время
// проверки должно быть возможно без переписывания пайплайна.
//
// СОСТОЯНИЕ: контракты и типы. Реализованы полностью только схемы и sanitizer — части, где
// решается корректность и где её можно проверить без ключей. Остальное ждёт доступов: ключа
// справочника карт, ключа поиска людей и адреса таблицы.

import type { CleanCompany, Enrichment, Lead, LeadScore, LeadSearchRequest, RawPlace } from './schemas.ts'
import type { RejectReason } from './sanitizer.ts'

/* ─────────────────────────────  1. Поиск  ───────────────────────────── */

export interface SearchStats {
  /** Сколько страниц выдачи забрали. Чужой API платный: расход должен быть виден, а не угадан. */
  pages: number
  /** Достигнут ли лимит запроса — или выдача просто кончилась раньше. Это разные исходы. */
  exhausted: boolean
}

export interface PlacesSearch {
  /**
   * Постранично тянет выдачу до лимита.
   *
   * Обязан соблюдать паузу между страницами: справочник отдаёт токен следующей страницы не сразу,
   * и запрос без задержки возвращает пустоту, которую легко принять за конец выдачи.
   */
  search(request: LeadSearchRequest): Promise<{ places: RawPlace[]; stats: SearchStats }>
}

/* ─────────────────────────────  2. Очистка  ───────────────────────────── */

export interface SanitizeReport {
  companies: CleanCompany[]
  /** Отброшенное с причиной. «Нашли 12 из 50» без объяснения читается как поломка поиска. */
  rejected: Array<{ place_id: string; reason: RejectReason }>
  duplicates: number
}

/* ─────────────────────────────  3. Обогащение  ───────────────────────────── */

export interface Enricher {
  /**
   * Читает сайт компании и открытые источники.
   *
   * НЕ ДОЛЖЕН падать целиком из-за одного недоступного сайта: обогащение — улучшение, а не условие.
   * Компания без описания остаётся лидом; компания, потерянная из-за таймаута чужого сервера, — нет.
   */
  enrich(company: CleanCompany): Promise<Enrichment>
}

/* ─────────────────────────────  4. Оценка  ───────────────────────────── */

export interface Scorer {
  /**
   * Сравнивает компанию с профилем идеального клиента.
   *
   * Статус выводится из числа порогом, а не берётся из ответа модели: модель охотно ставит «HOT»
   * рядом с оценкой 45, если формулировка ей понравилась.
   */
  score(company: CleanCompany, enrichment: Enrichment, icp: string): Promise<LeadScore | null>
}

/* ─────────────────────────────  5. Доставка  ───────────────────────────── */

export interface Notifier {
  /**
   * Сообщает о горячем лиде немедленно.
   *
   * ТОЛЬКО о горячих. Уведомление о каждом найденном лиде превращается в поток, который выключают
   * на второй день, и вместе с ним выключают те три сообщения в неделю, ради которых всё делалось.
   */
  alertHot(lead: Lead): Promise<{ ok: boolean; error?: string }>
}

export interface SheetSync {
  /** Дописывает строки в таблицу. Идемпотентно по dedupe_key: повтор не должен плодить строки. */
  append(leads: Lead[]): Promise<{ added: number; skipped: number }>
}

/** Постоянное хранилище лидов (Postgres/Supabase) — тот же контракт идемпотентности, что у SheetSync. */
export interface LeadStore {
  save(leads: Lead[]): Promise<{ added: number; skipped: number }>
}

/* ─────────────────────────────  Пайплайн  ───────────────────────────── */

export interface PipelineResult {
  found: number
  qualified: number
  hot: number
  leads: Lead[]
  rejected: SanitizeReport['rejected']
  duplicates: number
  /** Что не доехало и почему: сервис обогащения, оценка, таблица, уведомление. */
  failures: Array<{ stage: 'search' | 'enrich' | 'score' | 'store' | 'notify'; detail: string }>
}

/**
 * Задержка с ростом — общая для всех чужих API.
 *
 * Повтор без паузы по лимиту запросов не «пробует ещё раз», а добивает квоту: сервис отвечает 429
 * ровно потому, что запросов слишком много. Реализация одна на все сервисы, чтобы каждый не
 * заводил свою.
 */
export function backoffDelays(attempts = 4, baseMs = 800): number[] {
  return Array.from({ length: attempts }, (_, index) => baseMs * 2 ** index)
}
