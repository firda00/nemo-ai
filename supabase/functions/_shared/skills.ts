// Best-matching skill for a role string (+ optional extra signal like the agent's tasks).
// Scores by distinct matched keywords; returns the top skill or null when nothing matches.
export function matchSkill(roleText: string, extra = ''): RoleSkill | null {
  const hay = `${roleText} ${extra}`.toLowerCase()
  let best: RoleSkill | null = null
  let bestScore = 0
  for (const s of ROLE_SKILLS) {
    let score = 0
    for (const kw of s.match) if (kw && hay.includes(kw.toLowerCase())) score++
    if (score > bestScore) {
      bestScore = score
      best = s
    }
  }
  return bestScore > 0 ? best : null
}

// Embodiment block to append to a system prompt for a role, or '' if no skill matches.
export function roleSkillBlock(roleText: string, extra = ''): string {
  const s = matchSkill(roleText, extra)
  if (!s) return ''
  return `\n\n=== ВОЙДИ В РОЛЬ: ${s.label} ===\nДействуй как настоящий специалист этой профессии.\n${s.block}`
}
