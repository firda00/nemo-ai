// ROLE SKILLS — persona-EMBODIMENT modules that make an agent inhabit its profession.
//
// Every Nemo agent has a role (sales, copywriter, analyst, QA…). A generic "assistant"
// prompt makes every agent sound the same. A role skill injects HOW that profession actually
// thinks — its method/framework, its quality bar, its voice, and the anti-patterns to avoid —
// so the agent gets into character instead of answering blandly. Skills are matched by keyword
// against the agent's role (+ its tasks) at runtime and appended to the system prompt for
// single agents, the team lead, and each specialist sub-agent.

export interface RoleSkill {
  id: string
  label: string
  match: string[] // lowercase RU+EN keywords/synonyms that identify this role
  block: string // the embodiment text injected into the system prompt
}

