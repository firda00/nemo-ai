/*
 * ОДИН АДРЕС ВИДЖЕТА НА ВСЁ ПРИЛОЖЕНИЕ.
 *
 * Сниппет собирался в трёх местах, и в двух из них хост был один, а в третьем — другой:
 * страница интеграций и список каналов отдавали клиенту старый тестовый IP-домен, онбординг —
 * `cdn.nemo.ai`. Клиент получал разный код в зависимости от того, откуда копировал, и работать мог
 * максимум один из двух. Отказ при этом наступал не у нас, а у клиента на его сайте — то есть там,
 * где мы его не увидим.
 *
 * Теперь адрес один и берётся из окружения сборки. Значения по умолчанию нет намеренно: молчаливая
 * подстановка чужого хоста — это ровно тот случай, который здесь и разбирается.
 */

const GATEWAY = String(import.meta.env.VITE_API_GATEWAY_URL ?? '').trim().replace(/\/+$/, '')

/** Настроен ли адрес шлюза. Ложь — сниппет показывать нечего, и надо сказать об этом прямо. */
export const widgetHostConfigured = GATEWAY.length > 0

/**
 * Готовый сниппет для вставки на сайт клиента.
 *
 * Без настроенного шлюза возвращает null, а не строку с пустым адресом: сниппет вида
 * `src="/widget.js"` выглядит рабочим, копируется и молча не подключается.
 */
export function widgetSnippet(channelId: string): string | null {
  if (!widgetHostConfigured) return null
  return `<script src="${GATEWAY}/widget.js" data-channel="${channelId}" async></script>`
}
