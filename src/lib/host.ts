/*
 * Разделение по хосту: корневой домен — промо, субдомен app.* — личный кабинет.
 *
 * ЧИСТОЙ ФУНКЦИЕЙ, а не чтением window внутри компонента: правило про хосты проверяется таблицей
 * значений, а не поднятием сайта на пяти доменах. Ошибка здесь стоит дорого и в обе стороны —
 * посетитель промо-страницы, которого выкинуло в кабинет, и клиент, которому вместо кабинета
 * показали рекламу.
 */

/** Хосты разработки. На них разделения НЕТ: там один сервер отдаёт и промо, и кабинет. */
const DEV_HOSTS = new Set(['localhost', '127.0.0.1', '0.0.0.0', '::1'])

/**
 * Это хост личного кабинета?
 *
 * Признак — метка `app` первым уровнем имени. Проверяется именно ПЕРВЫЙ уровень, а не вхождение
 * подстроки: `myapp.example.com` и `example.com/app` — не кабинет, а `includes('app')` считал бы их
 * им и уводил посетителей промо-страницы в форму входа.
 */
export function isAppHost(hostname: string): boolean {
  const host = String(hostname ?? '').trim().toLowerCase().split(':')[0]
  if (!host || DEV_HOSTS.has(host)) return false
  return host.startsWith('app.')
}

/**
 * Куда вести запрос корня.
 *
 * На хосте кабинета «/» — это кабинет, а не промо: человек, набравший app.nemo.uz, идёт работать, и
 * показывать ему рекламу продукта, которым он уже пользуется, невежливо.
 *
 * Возвращает null, когда перенаправлять не нужно, — вызывающий код тогда рендерит обычный маршрут.
 */
export function rootRedirectFor(hostname: string): string | null {
  return isAppHost(hostname) ? '/app' : null
}
