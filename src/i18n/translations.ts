// Built by deep-merging an English override onto the RU base, so the shape always
// matches `typeof uz` exactly (any key not yet translated falls back to Russian).
type DeepPartial<T> = T extends string | number | boolean
  ? T
  : T extends Array<infer U>
    ? Array<DeepPartial<U>>
    : { [K in keyof T]?: DeepPartial<T[K]> }

function deepMerge<T>(base: T, over: unknown): T {
  if (Array.isArray(over)) return over as T
  if (over && typeof over === 'object' && base && typeof base === 'object' && !Array.isArray(base)) {
    const out: Record<string, unknown> = { ...(base as Record<string, unknown>) }
    for (const k of Object.keys(over as Record<string, unknown>)) {
      out[k] = deepMerge((base as Record<string, unknown>)[k], (over as Record<string, unknown>)[k])
    }
    return out as T
  }
  return (over === undefined ? base : over) as T
}

